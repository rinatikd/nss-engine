// Browser-only persistent credential. Never export it to a page, log it,
// write to source control, or expose it through an MCP tool.
const KEY = 'browserToken';

// Chrome exposes storage.local to content scripts by default. Restrict it to
// trusted extension contexts BEFORE any read/write of persistent credentials.
// Fail closed if the installed Chrome cannot enforce this boundary.
export async function restrictCredentialStorage(chromeApi) {
  if (typeof chromeApi?.storage?.local?.setAccessLevel !== 'function')
    throw Error('SECURE_STORAGE_UNAVAILABLE');
  await chromeApi.storage.local.setAccessLevel({ accessLevel: 'TRUSTED_CONTEXTS' });
}

export async function loadBrowserKey(chromeApi) {
  await restrictCredentialStorage(chromeApi);
  const saved = (await chromeApi.storage.local.get(KEY))[KEY];
  if (typeof saved === 'string' && saved.length > 0)
    return { value: saved, persistent: true };
  // Preserve existing authorization from previous temporary sessions until
  // the user clicks Connect. Migration to persistent storage is opt-in there.
  const session = (await chromeApi.storage.session.get(KEY))[KEY];
  return { value: typeof session === 'string' ? session : '', persistent: false };
}

export async function saveBrowserKey(chromeApi, value) {
  await restrictCredentialStorage(chromeApi);
  if (typeof value !== 'string' || !value.trim()) throw Error('BROWSER_KEY_REQUIRED');
  // The key is generated by Setup-Windows.ps1/server config; never regenerate.
  const key = value.trim();
  await chromeApi.storage.local.set({ [KEY]: key });
  await chromeApi.storage.session.remove(KEY);
  return true;
}

export async function forgetBrowserKey(chromeApi) {
  await restrictCredentialStorage(chromeApi);
  await chromeApi.storage.local.remove(KEY);
  await chromeApi.storage.session.remove(KEY);
}
