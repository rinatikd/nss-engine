# ---- Вывод в DXF ----
COL = {"ДОРОГА": 8, "ДОРОГА-ДОСМОТР": 8, "ДОРОГА-РАЗМЕТКА": 7, "СТЕНА-ЖБ": 7, "АР-СТЕНЫ": 7, "АР-ПЕРЕГОРОДКИ": 7, "АР-ДВЕРИ": 3,
       "АР-ОКНА": 5, "МЕБЕЛЬ": 6, "МЕБЕЛЬ-РЕНТГЕН": 1, "САНТЕХ": 6, "БОЛЛАР": 2, "АР-БАЛЮСТРАДА": 8, "СС-ТУРНИКЕТ": 4, "СС-КАЛИТКА": 4,
       "СС-МД": 4, "СС-ТЕРМИНАЛ": 4, "СС-ШЛАГБАУМ": 4, "СС-БЛОКЕР": 1, "СС-КАМЕРА": 3, "СС-ОБЗОР": 3, "АР-КОЗЫРЁК": 9, "ПОЗИЦИИ": 2,
       "ТЕКСТ": 7, "РАЗМЕРЫ": 2}
def dxf(path):
    out = ["0", "SECTION", "2", "HEADER", "9", "$ACADVER", "1", "AC1009", "9", "$INSUNITS", "70", "4", "0", "ENDSEC",
           "0", "SECTION", "2", "TABLES", "0", "TABLE", "2", "LAYER", "70", str(len(COL))]
    for n, c in COL.items(): out += ["0", "LAYER", "2", n, "70", "0", "62", str(c), "6", "CONTINUOUS"]
    out += ["0", "ENDTAB", "0", "ENDSEC", "0", "SECTION", "2", "ENTITIES"]
    f = lambda v: "%.1f" % (v * 1000)
    def line(l, a, b): out.extend(["0", "LINE", "8", l, "10", f(a[0]), "20", f(a[1]), "30", "0", "11", f(b[0]), "21", f(b[1]), "31", "0"])
    def text(l, p, s, h, anchor="l"):
        out.extend(["0", "TEXT", "8", l, "10", f(p[0]), "20", f(p[1]), "30", "0", "40", f(h), "1", s])
    for l, t, d in P:
        if t == "line": line(l, *d)
        elif t == "rect":
            x0, y0, x1, y1, _ = d
            for a, b in (((x0, y0), (x1, y0)), ((x1, y0), (x1, y1)), ((x1, y1), (x0, y1)), ((x0, y1), (x0, y0))): line(l, a, b)
        elif t == "circle": out.extend(["0", "CIRCLE", "8", l, "10", f(d[0][0]), "20", f(d[0][1]), "30", "0", "40", f(d[1])])
        elif t == "arc": out.extend(["0", "ARC", "8", l, "10", f(d[0][0]), "20", f(d[0][1]), "30", "0", "40", f(d[1]), "50", str(d[2]), "51", str(d[3])])
        elif t == "text": text(l, d[0] if d[3] == "l" else (d[0][0] - len(d[1]) * d[2] * .25, d[0][1]), d[1], d[2])
        elif t == "badge":
            x, y, n = d; out.extend(["0", "CIRCLE", "8", l, "10", f(x), "20", f(y), "30", "0", "40", f(0.3)]); text(l, (x - .12 * len(str(n)), y - .11), str(n), .25)
        elif t == "fov":
            x, y, az, fov, r = d; a0, a1 = az - fov / 2, az + fov / 2
            for a in (a0, a1): line(l, (x, y), (x + r * math.cos(math.radians(a)), y + r * math.sin(math.radians(a))))
            out.extend(["0", "ARC", "8", l, "10", f(x), "20", f(y), "30", "0", "40", f(r), "50", str(a0 % 360), "51", str(a1 % 360)])
        elif t == "dim":
            a, b, _, lab = d; line(l, a, b); text(l, ((a[0] + b[0]) / 2 - .6, (a[1] + b[1]) / 2 + (.2 if a[1] == b[1] else 0)), lab, .2)
    out += ["0", "ENDSEC", "0", "EOF"]
    with open(path, "w", encoding="utf-8") as fh: fh.write("\n".join(out) + "\n")

# ---- PNG ----
def png(path):
    import matplotlib; matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    from matplotlib.patches import Rectangle, Wedge
    fig, ax = plt.subplots(figsize=(16, 9.5))
    sty = {"ДОРОГА": ("#9aa0a6", 1.0), "ДОРОГА-ДОСМОТР": ("#9aa0a6", 1.0), "ДОРОГА-РАЗМЕТКА": ("#d93025", 2), "СТЕНА-ЖБ": ("#202124", 2.5),
           "АР-СТЕНЫ": ("#202124", 2.0), "АР-ПЕРЕГОРОДКИ": ("#5f6368", 1.5), "АР-ДВЕРИ": ("#188038", 2.5), "АР-ОКНА": ("#1a73e8", 2.5),
           "МЕБЕЛЬ": ("#80868b", 1.0), "МЕБЕЛЬ-РЕНТГЕН": ("#d93025", 1.0), "САНТЕХ": ("#80868b", 1.0), "БОЛЛАР": ("#e37400", 1.0),
           "АР-БАЛЮСТРАДА": ("#9aa0a6", 1.0), "СС-ТУРНИКЕТ": ("#1967d2", 1.5), "СС-КАЛИТКА": ("#1967d2", 1.5), "СС-МД": ("#1967d2", 1.5),
           "СС-ТЕРМИНАЛ": ("#1967d2", 2.0), "СС-ШЛАГБАУМ": ("#e37400", 2.5), "СС-БЛОКЕР": ("#d93025", 3), "СС-КАМЕРА": ("#188038", 1.5),
           "АР-КОЗЫРЁК": ("#9aa0a6", 1.0), "ТЕКСТ": ("#202124", 1), "РАЗМЕРЫ": ("#5f6368", 1)}
    for l, t, d in P:
        c, w = sty.get(l, ("#000", 1))
        if t == "line": ax.plot([d[0][0], d[1][0]], [d[0][1], d[1][1]], color=c, lw=w)
        elif t == "rect":
            x0, y0, x1, y1, _ = d
            fill = {"СТЕНА-ЖБ": "#202124", "АР-СТЕНЫ": "none", "СС-ТЕРМИНАЛ": c, "АР-ДВЕРИ": "#e6f4ea", "АР-ОКНА": "#e8f0fe"}.get(l, "none")
            ls = "--" if l == "АР-КОЗЫРЁК" or l == "МЕБЕЛЬ-РЕНТГЕН" else "-"
            ax.add_patch(Rectangle((x0, y0), x1 - x0, y1 - y0, fill=fill != "none", fc=fill if fill != "none" else "none", ec=c, lw=w, ls=ls, zorder=3))
        elif t == "circle": ax.add_patch(plt.Circle(d[0], d[1], fill=(l in ("БОЛЛАР", "СС-КАМЕРА")), fc=c if l in ("БОЛЛАР", "СС-КАМЕРА") else "none", ec=c, lw=w, zorder=4))
        elif t == "arc": ax.add_patch(Wedge(d[0], d[1], d[2], d[3], fill=False, ec=c, lw=w, ls=":"))
        elif t == "text":
            ax.text(d[0][0], d[0][1], d[1], fontsize=max(6, d[2] * 26), ha="left" if d[3] == "l" else "center", va="center", color=c, zorder=6)
        elif t == "badge":
            x, y, n = d; ax.add_patch(plt.Circle((x, y), .42, fc="white", ec="#c5221f", lw=1.5, zorder=7)); ax.text(x, y, str(n), ha="center", va="center", fontsize=9, zorder=8, color="#c5221f", fontweight="bold")
        elif t == "fov":
            x, y, az, fov, r = d; ax.add_patch(Wedge((x, y), r, az - fov / 2, az + fov / 2, fc="#188038", alpha=.12, ec="none", zorder=1))
        elif t == "dim":
            a, b, _, lab = d; ax.plot([a[0], b[0]], [a[1], b[1]], color=c, lw=.8); ax.text((a[0] + b[0]) / 2, (a[1] + b[1]) / 2 + (.35 if a[1] == b[1] else 0), lab, fontsize=7, color=c, ha="center", rotation=0 if a[1] == b[1] else 90, va="center")
    for n, a, b, c_, d_ in doors: ax.text((a + c_) / 2, (b + d_) / 2 + 0.6, n.split(" ")[0], fontsize=7, color="#188038", ha="center")
    for n, a, b, c_, d_ in wins: ax.text((a + c_) / 2, (b + d_) / 2 + (-.55 if b < 14 else .55), n, fontsize=7, color="#1a73e8", ha="center")
    ax.set_xlim(-27, 25.5); ax.set_ylim(-7.5, 29); ax.set_aspect("equal"); ax.axis("off")
    ax.set_title("Типовой КПП, план на отм. 0,000 (пост +0,300). Размеры в мм/м, ось X — снаружи внутрь", fontsize=11)
    fig.savefig(path, dpi=110, bbox_inches="tight", facecolor="white"); plt.close(fig)

def main(argv=None):
    import argparse
    ap = argparse.ArgumentParser(description="Типовой КПП: DXF (R12, мм) и PNG-превью. Результаты в Git не добавляются (.dxf запрещён repo_guard).")
    ap.add_argument("--out-dir", default="output/kpp_plan", help="каталог результатов (по умолчанию output/kpp_plan, игнорируется Git)")
    ap.add_argument("--no-png", action="store_true", help="не строить PNG (matplotlib не нужен)")
    a = ap.parse_args(argv)
    import os
    os.makedirs(a.out_dir, exist_ok=True)
    dxf(os.path.join(a.out_dir, "kpp_plan.dxf"))
    if not a.no_png: png(os.path.join(a.out_dir, "kpp_plan.png"))
    print("primitives:", len(P)); return 0

if __name__ == "__main__":
    raise SystemExit(main())
