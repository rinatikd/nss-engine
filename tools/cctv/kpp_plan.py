D("РАЗМЕРЫ", (-24.5, 3.5), (-24.5, 7.0), 0, "3500"); D("РАЗМЕРЫ", (-24.5, 7.0), (-24.5, 8.5), 0, "1500"); D("РАЗМЕРЫ", (-24.5, 8.5), (-24.5, 12.0), 0, "3500")
D("РАЗМЕРЫ", (-24.5, 12.5), (-24.5, 17.0), 0, "4500"); D("РАЗМЕРЫ", (-24.5, 17.1), (-24.5, 21.6), 0, "4500")
