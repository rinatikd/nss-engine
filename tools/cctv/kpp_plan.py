T("ТЕКСТ", (-20, 5.0), "ВЪЕЗД  >>", 0.35); T("ТЕКСТ", (-20, 10.0), "<<  ВЫЕЗД", 0.35)
T("ТЕКСТ", (-20, 18.5), "Пешеходный блок", 0.3)
