# Типовой КПП: геометрия (м) -> DXF (мм, R12) + PNG. Ось X — по движению снаружи внутрь, Y — на север.
import sys, math, json

P = []   # примитивы: (слой, тип, данные)
def L(layer, a, b): P.append((layer, "line", (a, b)))
def R(layer, x0, y0, x1, y1, fill=None):
    P.append((layer, "rect", (x0, y0, x1, y1, fill)))
def C(layer, c, r): P.append((layer, "circle", (c, r)))
def T(layer, p, s, h=0.2, anchor="l"): P.append((layer, "text", (p, s, h, anchor)))
def A(layer, c, r, a0, a1): P.append((layer, "arc", (c, r, a0, a1)))
def D(layer, a, b, off, label):  # размер: линия + выноски + текст
    P.append((layer, "dim", (a, b, off, label)))

# ---- Дорога ----
IN = (3.5, 7.0); ISL = (7.0, 8.5); OUT = (8.5, 12.0)
