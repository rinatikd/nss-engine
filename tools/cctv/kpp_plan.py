for n, a, b, c, d in wins:
    R("АР-ОКНА", a, b, c, d)
# оборудование в посту
R("МЕБЕЛЬ", -1.0, 13.0, 2.0, 13.8)             # консоль (2 места)
C("МЕБЕЛЬ", (-0.2, 14.3), 0.25); C("МЕБЕЛЬ", (1.2, 14.3), 0.25)
R("МЕБЕЛЬ", 1.9, 16.1, 2.5, 16.7)              # шкаф 19" ШС
R("МЕБЕЛЬ", -4.1, 13.0, -2.9, 13.6)            # стол досмотра
R("МЕБЕЛЬ-РЕНТГЕН", -4.1, 15.6, -2.5, 16.4)    # рентген (только КПП-1)
C("САНТЕХ", (3.5, 13.3), 0.2); R("САНТЕХ", 2.9, 12.85, 3.4, 13.15)
