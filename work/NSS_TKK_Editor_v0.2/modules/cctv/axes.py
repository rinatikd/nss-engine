"""Привязка точки к разбивочным осям 1 этажа (слой ОСИ): «ось 3 → 1,2 м вправо, ось Б ← 0,4 м вверх»."""
import math
V = {"1": 58689, "2": 64689, "3": 68589, "4": 74589, "5": 80089, "6": 85639, "7": 91939, "8": 99139, "9": 106339}
H = {"А": -211846, "Б": -203946, "Б/1": -202196, "В": -197946, "Г": -194646, "Д": -191946, "Е": -183546}

def ref(x, y):
    kv = min(V, key=lambda k: abs(V[k] - x)); kh = min(H, key=lambda k: abs(H[k] - y))
    dx = (x - V[kv]) / 1000; dy = (y - H[kh]) / 1000
    sx = "вправо" if dx >= 0 else "влево"; sy = "вверх" if dy >= 0 else "вниз"
    return f"от оси {kv}: {abs(dx):.1f} м {sx}; от оси {kh}: {abs(dy):.1f} м {sy}"

def compass(a):
    names = ["В", "СВ", "С", "СЗ", "З", "ЮЗ", "Ю", "ЮВ"]  # 0°=вправо по плану (восток), 90°=вверх (север)
    return names[int(((a % 360) + 22.5) // 45) % 8]
