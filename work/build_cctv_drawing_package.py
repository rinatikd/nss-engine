def add_layer(name, color):
    if name not in doc.layers:
        doc.layers.new(name, dxfattribs={"color": color, "lineweight": 25})

for name, col in [("СВН_ЛИСТЫ", BLACK), ("СВН_СХЕМЫ", BLUE), ("СВН_ПРИМЕЧАНИЯ", RED)]:
    add_layer(name, col)

def line(msp, a, b, layer="СВН_ЛИСТЫ", color=None, width=25):
    at = {"layer": layer, "lineweight": width}
    if color is not None: at["color"] = color
    msp.add_line(a, b, dxfattribs=at)

def rect(msp, x1, y1, x2, y2, layer="СВН_ЛИСТЫ", color=None, width=25):
    pts = [(x1,y1),(x2,y1),(x2,y2),(x1,y2),(x1,y1)]
    at = {"layer": layer, "lineweight": width}
    if color is not None: at["color"] = color
    msp.add_lwpolyline(pts, dxfattribs=at)

def txt(msp, s, x, y, h=3.2, color=None, layer="СВН_ЛИСТЫ", align=None):
    at = {"layer": layer, "height": h, "style": STYLE}
    if color is not None: at["color"] = color
    ent = msp.add_text(s, dxfattribs=at)
    if align is None: ent.dxf.insert = (x,y,0)
    else: ent.set_placement((x,y), align=align)
    return ent

def mtxt(msp, s, x, y, w, h=3.0, color=None, layer="СВН_ЛИСТЫ"):
    at = {"layer": layer, "char_height": h, "width": w, "style": STYLE, "attachment_point": 1}
    if color is not None: at["color"] = color
    return msp.add_mtext(s, dxfattribs=at).set_location((x,y))

