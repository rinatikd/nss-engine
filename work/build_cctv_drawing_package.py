def box(p, x,y,w,h,title,body, accent=BLUE):
    rect(p,x,y,x+w,y+h,color=accent)
    txt(p,title,x+4,y+h-8,3.2,accent)
    line(p,(x+4,y+h-12),(x+w-4,y+h-12),color=accent)
    mtxt(p,body,x+4,y+h-17,w-8,2.6)

def table(p,x,y,width,headers,rows,colwidths,rowh=9,fs=2.5):
    xx=[x]
    for cw in colwidths: xx.append(xx[-1]+cw)
    total_h=rowh*(len(rows)+1)
    rect(p,x,y-total_h,x+width,y)
    for xv in xx[1:-1]: line(p,(xv,y),(xv,y-total_h))
    for j in range(1,len(rows)+1): line(p,(x,y-j*rowh),(x+width,y-j*rowh))
    for i,v in enumerate(headers): txt(p,str(v),xx[i]+1.5,y-rowh+3,fs,BLUE)
    for r,row in enumerate(rows):
        for i,v in enumerate(row):
            txt(p,str(v),xx[i]+1.5,y-(r+2)*rowh+3,fs)

