source_doc = ezdxf.readfile(SOURCE)
# Keep the site context editable while removing legacy AEC proxy dictionaries that
# cause Core Console to crash when it re-saves the full consultant DXF.
doc = ezdxf.new("R2018")
doc.header["$INSUNITS"] = 4
imp = Importer(source_doc, doc)
keep_types = {"LWPOLYLINE", "LINE", "CIRCLE", "ARC", "INSERT", "MTEXT", "TEXT", "SOLID"}
window = (5300, -11250, 6850, -10400)
selected = []
for entity in source_doc.modelspace():
    if entity.dxftype() not in keep_types:
        continue
    try:
        ext = bbox.extents([entity], fast=True)
        if not ext.has_data:
            continue
        if ext.extmax.x < window[0] or ext.extmin.x > window[2] or ext.extmax.y < window[1] or ext.extmin.y > window[3]:
            continue
        selected.append(entity)
    except Exception:
        continue
imp.import_entities(selected, doc.modelspace())
imp.finalize()
doc.header["$MEASUREMENT"] = 1
doc.header["$LUNITS"] = 2
doc.header["$LUPREC"] = 2

